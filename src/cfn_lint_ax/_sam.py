# `Api` and `HttpApi` events create an implicit api, which in turn generates
# everything the explicit api resource would generate.
SAM_IMPLICIT_API_EVENT_TYPES = {
    "Api": "AWS::Serverless::Api",
    "HttpApi": "AWS::Serverless::HttpApi",
}


def deployed_resource_types(cfn: Template) -> set[str] | None:
    """
    Return the resource types CloudFormation deploys the template as.

    `AWS::Serverless::*` resources are replaced by the resource types they
    generate. Returns `None` if the template uses a SAM resource whose
    generated resource types are unknown.
    """

    resource_types: set[str] = set()

    for resource in cfn.get_resources().values():
        resource_type = resource.get("Type")
        if not isinstance(resource_type, str):
            continue

        if not resource_type.startswith(SAM_RESOURCE_TYPE_PREFIX):
            resource_types.add(resource_type)
            continue

        generated_resource_types = SAM_GENERATED_RESOURCE_TYPES.get(resource_type)
        if generated_resource_types is None:
            return None

        resource_types |= generated_resource_types
        resource_types |= _implicit_api_resource_types(resource)

    return resource_types


def _implicit_api_resource_types(resource: dict[str, Any]) -> set[str]:
    resource_types: set[str] = set()

    for _, event_type, _ in serverless_function_events(resource):
        implicit_api_type = SAM_IMPLICIT_API_EVENT_TYPES.get(event_type)
        if implicit_api_type is not None:
            resource_types |= SAM_GENERATED_RESOURCE_TYPES[implicit_api_type]

    return resource_types


def serverless_function_events(
    resource: dict[str, Any],
) -> Iterator[ServerlessEvent]:
    """
    Yield `(name, type, properties)` for every event of a SAM resource.

    Malformed entries are skipped: cfn-lint's schema validation reports those,
    a rule should not report them a second time.
    """

    properties = resource.get("Properties")
    if not isinstance(properties, dict):
        return

    events = properties.get("Events")
    if not isinstance(events, dict):
        return

    for event_name, event in events.items():
        if not isinstance(event, dict):
            continue
        event_type = event.get("Type")
        if not isinstance(event_type, str):
            continue
        event_properties = event.get("Properties")
        if not isinstance(event_properties, dict):
            event_properties = {}
        yield event_name, event_type, event_properties
